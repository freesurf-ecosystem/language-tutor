// Bundles the sentence illustrations into one offline HTML string for the in-app WebView panel.
// Source of truth: ../illustrations/scenes/ (sketch.js, panel.js, one file per illustrated story).
// Also copies the scene files into the HyperFrames preview project so both stay identical.
//
//   npm run illustrations
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, "..");
const scenesDir = join(app, "..", "illustrations", "scenes");
const STORIES = ["fox"]; // story ids (match tutor-app/src/data/story.ts) that have scene files

const read = (p) => readFileSync(p, "utf8");
const gsap = read(join(app, "node_modules", "gsap", "dist", "gsap.min.js"));
const parts = [read(join(scenesDir, "sketch.js")), ...STORIES.map((id) => read(join(scenesDir, `${id}.js`))), read(join(scenesDir, "panel.js"))];

const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>html,body{margin:0;height:100%;background:#FFFBF5;overflow:hidden}svg{width:100%;height:100%;display:block}</style></head>
<body><svg id="stage" viewBox="-20 420 1000 600" preserveAspectRatio="xMidYMax meet">
<defs><filter id="boil" x="-10%" y="-10%" width="120%" height="120%"><feTurbulence id="turb" type="fractalNoise" baseFrequency="0.02" numOctaves="2" seed="1" result="n"/><feDisplacementMap in="SourceGraphic" in2="n" scale="4"/></filter></defs>
<g filter="url(#boil)"><g id="sky"></g><path d="M-20 960 L 980 960" style="fill:none;stroke:#211B14;stroke-width:5;stroke-linecap:round"/><g id="layer"></g></g></svg>
${[gsap, ...parts].map((js) => `<script>${js}</script>`).join("\n")}
</body></html>`;

const outDir = join(app, "src", "illustrations");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "sceneHtml.ts"),
  `// GENERATED by scripts/build-illustrations.mjs from ../illustrations/scenes. Do not edit; run \`npm run illustrations\`.\n` +
  `export const SCENE_HTML: string = ${JSON.stringify(html)};\n` +
  `export const ILLUSTRATED_STORIES: string[] = ${JSON.stringify(STORIES)};\n`);

// keep the HyperFrames preview project in sync
const hf = join(app, "..", "illustrations", "fox-and-the-grapes", "assets");
if (existsSync(hf)) { copyFileSync(join(scenesDir, "sketch.js"), join(hf, "sketch.js")); copyFileSync(join(scenesDir, "fox.js"), join(hf, "fox.js")); }

console.log(`sceneHtml.ts: ${(html.length / 1024).toFixed(0)} KB, stories: ${STORIES.join(", ")}`);
