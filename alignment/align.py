#!/usr/bin/env python3
"""
Word-level alignment for the read-along tutor.

Given the audio of a spoken sentence (generated by Qwen3-TTS via Together AI)
plus the known text, this produces per-word start/end timestamps so the app can
highlight each word as it is read.

Approach: `faster-whisper` (free, CPU-only) transcribes the *clean synthetic* TTS
audio with `word_timestamps=True`. Because the audio is synthetic and we already
know the text, the word boundaries come out accurate enough for a read-along
highlight. This is the self-hosted, $0 alternative to a per-call timestamp API.

Usage:
    python align.py audio.wav [--text "The sentence that was spoken"] [--output out.json]

Notes:
  * `faster-whisper` fetches model weights from Hugging Face on first run
    (default model: guillaumekln/faster-whisper-base.en, a non-gated mirror).
    If you have a stale/expired HF token in your env, it can 401 — run with
    HF_TOKEN / HUGGING_FACE_HUB_TOKEN unset, or set a valid token.
  * Python 3.14 removed `metadata_errors` from PyAV, which faster-whisper still
    passes; the small monkey-patch below works around it. On Python 3.11/3.12
    with `av<14` you can drop the patch.
"""

import argparse
import json
import sys

import av

# Workaround for PyAV >= 14 (e.g. Python 3.14): strip the removed kwarg.
_orig_open = av.open


def _open(*args, **kwargs):
    kwargs.pop("metadata_errors", None)
    return _orig_open(*args, **kwargs)


av.open = _open

from faster_whisper import WhisperModel  # noqa: E402


def align(audio_path: str, model_name: str) -> list[dict]:
    model = WhisperModel(model_name, device="cpu", compute_type="int8")
    segments, _info = model.transcribe(audio_path, word_timestamps=True, language="en")
    words = []
    for seg in segments:
        for w in seg.words:
            words.append({
                "word": w.word.strip(),
                "start": round(w.start, 3),
                "end": round(w.end, 3),
            })
    return words


def main() -> None:
    p = argparse.ArgumentParser(description="Word-level alignment for read-along audio")
    p.add_argument("audio", help="Path to the WAV/MP3 sentence audio")
    p.add_argument("--text", help="Known text (informational only for this approach)")
    p.add_argument("--model", default="guillaumekln/faster-whisper-base.en",
                   help="faster-whisper model repo id (non-gated mirror by default)")
    p.add_argument("--output", help="Optional path to write JSON to")
    args = p.parse_args()

    words = align(args.audio, args.model)
    result = {"text": args.text, "words": words}

    out = json.dumps(result, indent=2)
    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(out + "\n")
    print(out)


if __name__ == "__main__":
    main()
